/**
 * exporters.ts — turn a Morph into files people can ship.
 * Every exporter is a pure function (string in, string out): no DOM, runs anywhere.
 *
 *   toAnimatedSVG   self-contained SVG with SMIL <animate> (plays in every browser, in <img>, in email clients that render SVG)
 *   toReactToggle   a dependency-free React component driven by an `active` prop
 *   toCSS           @keyframes on the CSS `d` property (Chromium + Firefox)
 *   toLottie        Bodymovin/Lottie JSON (iOS, Android, web, Figma plugins, After Effects round-trips)
 *   MORPH_TOOL      a JSON-schema tool definition so an LLM agent can call the engine
 */
import { createMorph, type Morph, type ShapeStyle, parseColor, type MorphOptions } from "./engine";

const EASE = "0.65 0 0.35 1"; // cubic-bezier close to easeInOutCubic

const n = (v: number) => +v.toFixed(3);

function paintAttrs(s: ShapeStyle, color?: string): string {
  const c = (v: string | null) => (v === null ? "none" : v === "currentColor" && color ? color : v);
  const parts = [`fill="${c(s.fill)}"`];
  if (s.fill && s.fillRule === "evenodd") parts.push(`fill-rule="evenodd"`);
  if (s.stroke) {
    parts.push(`stroke="${c(s.stroke)}"`, `stroke-width="${n(s.strokeWidth)}"`);
    if (s.lineCap !== "butt") parts.push(`stroke-linecap="${s.lineCap}"`);
    if (s.lineJoin !== "miter") parts.push(`stroke-linejoin="${s.lineJoin}"`);
  }
  return parts.join(" ");
}

export interface SvgExportOptions {
  /** Seconds for one A→B transition. */
  duration?: number;
  /** Seconds to rest on each state when looping. */
  hold?: number;
  /** Loop A→B→A forever, or play A→B once and stay. */
  loop?: boolean;
  /** Pixel size for width/height attributes. */
  size?: number;
  /** Replace currentColor (leave undefined to keep it themeable). */
  color?: string;
}

/** Animated SVG using SMIL. Works inline, in <img>, and as a standalone file. */
export function toAnimatedSVG(m: Morph, o: SvgExportOptions = {}): string {
  const dur = o.duration ?? 0.6,
    hold = o.hold ?? 0.6,
    loop = o.loop ?? true;
  const [vx, vy, vw, vh] = m.viewBox;
  const dA = m.d(0),
    dB = m.d(1);
  const sA = m.style(0),
    sB = m.style(1);
  const size = o.size ?? 96;
  const w = vw >= vh ? size : Math.round((size * vw) / vh);
  const h = vh >= vw ? size : Math.round((size * vh) / vw);

  let anim: string;
  if (loop) {
    const total = 2 * dur + 2 * hold;
    const k = [0, dur, dur + hold, 2 * dur + hold, total].map((x) => n(x / total)).join(";");
    const splines = [EASE, "0 0 1 1", EASE, "0 0 1 1"].join(";");
    anim = `<animate attributeName="d" dur="${n(
      total,
    )}s" repeatCount="indefinite" calcMode="spline" keyTimes="${k}" keySplines="${splines}" values="${dA};${dB};${dB};${dA};${dA}"/>`;
    if (sA.strokeWidth !== sB.strokeWidth && sA.stroke) {
      anim += `<animate attributeName="stroke-width" dur="${n(
        total,
      )}s" repeatCount="indefinite" calcMode="spline" keyTimes="${k}" keySplines="${splines}" values="${n(sA.strokeWidth)};${n(
        sB.strokeWidth,
      )};${n(sB.strokeWidth)};${n(sA.strokeWidth)};${n(sA.strokeWidth)}"/>`;
    }
  } else {
    anim = `<animate attributeName="d" dur="${n(
      dur,
    )}s" fill="freeze" calcMode="spline" keyTimes="0;1" keySplines="${EASE}" values="${dA};${dB}"/>`;
  }
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${n(vx)} ${n(vy)} ${n(vw)} ${n(vh)}">` +
    `<path ${paintAttrs(sA, o.color)} d="${dA}">${anim}</path></svg>`
  );
}

/** CSS keyframes on the `d` property. Chromium and Firefox; Safari needs the SVG/SMIL export. */
export function toCSS(m: Morph, o: { className?: string; duration?: number } = {}): string {
  const cls = o.className ?? "morph";
  const dur = o.duration ?? 0.6;
  const [vx, vy, vw, vh] = m.viewBox;
  return `/* Markup:
<svg viewBox="${n(vx)} ${n(vy)} ${n(vw)} ${n(vh)}" width="96" height="96">
  <path class="${cls}" ${paintAttrs(m.style(0))} />
</svg>
Supported in Chromium and Firefox. Use the animated SVG export for Safari. */

.${cls} {
  d: path("${m.d(0)}");
  transition: d ${dur}s cubic-bezier(${EASE.replace(/ /g, ", ")});
}
.${cls}.is-active {
  d: path("${m.d(1)}");
}

/* Or loop it: */
@keyframes ${cls}-loop {
  0%, 15%   { d: path("${m.d(0)}"); }
  50%, 65%  { d: path("${m.d(1)}"); }
  100%      { d: path("${m.d(0)}"); }
}
`;
}

/** A tiny React component (no dependencies) that morphs when `active` flips. Uses SMIL so it works in Safari too. */
export function toReactToggle(m: Morph, name = "MorphIcon", duration = 0.35): string {
  const [vx, vy, vw, vh] = m.viewBox;
  const s = m.style(0);
  const jsxPaint = paintAttrs(s)
    .replace(/fill-rule=/g, "fillRule=")
    .replace(/stroke-width=/g, "strokeWidth=")
    .replace(/stroke-linecap=/g, "strokeLinecap=")
    .replace(/stroke-linejoin=/g, "strokeLinejoin=");
  return `import { useEffect, useRef } from "react";

const A = "${m.d(0)}";
const B = "${m.d(1)}";

/** Generated by the vector morph engine: both paths share one command structure, so they interpolate cleanly. */
export function ${name}({ active = false, size = 24, label }: { active?: boolean; size?: number; label?: string }) {
  const toB = useRef<SVGAnimateElement>(null);
  const toA = useRef<SVGAnimateElement>(null);
  const mounted = useRef(false);

  useEffect(() => {
    if (!mounted.current) { mounted.current = true; return; }
    (active ? toB : toA).current?.beginElement();
  }, [active]);

  return (
    <svg width={size} height={size} viewBox="${n(vx)} ${n(vy)} ${n(vw)} ${n(
      vh,
    )}" role={label ? "img" : undefined} aria-label={label} aria-hidden={label ? undefined : true}>
      <path d={active ? B : A} ${jsxPaint}>
        <animate ref={toB} attributeName="d" begin="indefinite" dur="${duration}s" fill="freeze"
          calcMode="spline" keyTimes="0;1" keySplines="${EASE}" values={A + ";" + B} />
        <animate ref={toA} attributeName="d" begin="indefinite" dur="${duration}s" fill="freeze"
          calcMode="spline" keyTimes="0;1" keySplines="${EASE}" values={B + ";" + A} />
      </path>
    </svg>
  );
}
`;
}

/* ---------------------------------------------------------------------------
 * Lottie
 * ------------------------------------------------------------------------- */

export interface LottieOptions {
  fps?: number;
  duration?: number; // seconds per transition
  hold?: number; // seconds resting on each state
  size?: number; // output canvas size in px (longest side)
  color?: string; // used where the source says currentColor
  name?: string;
}

type LottieShape = { c: boolean; v: number[][]; i: number[][]; o: number[][] };

export function lottieColor(c: string | null, fallback: string): number[] {
  const rgb = parseColor(c === "currentColor" || !c ? fallback : c) ?? parseColor(fallback) ?? [0, 0, 0, 1];
  return [n(rgb[0] / 255), n(rgb[1] / 255), n(rgb[2] / 255), 1];
}

/** Lottie stores vertices plus in/out tangents relative to each vertex — a direct mapping of our cubic segments. */
export function lottieShapes(m: Morph, t: number): LottieShape[] {
  const buf = m.at(t, new Float32Array(m.plan.a.length));
  const [vx, vy] = m.viewBox;
  return m.plan.layout.map((L) => {
    const v: number[][] = [],
      ins: number[][] = [],
      outs: number[][] = [];
    let x = buf[L.offset] - vx,
      y = buf[L.offset + 1] - vy;
    v.push([n(x), n(y)]);
    ins.push([0, 0]);
    for (let j = 0; j < L.segs; j++) {
      const o = L.offset + 2 + j * 6;
      const c1x = buf[o] - vx,
        c1y = buf[o + 1] - vy,
        c2x = buf[o + 2] - vx,
        c2y = buf[o + 3] - vy;
      const ex = buf[o + 4] - vx,
        ey = buf[o + 5] - vy;
      outs[j] = [n(c1x - x), n(c1y - y)];
      const last = j === L.segs - 1;
      if (last && L.closed) {
        ins[0] = [n(c2x - ex), n(c2y - ey)]; // closing segment's in-tangent belongs to vertex 0
      } else {
        v.push([n(ex), n(ey)]);
        ins.push([n(c2x - ex), n(c2y - ey)]);
      }
      x = ex;
      y = ey;
    }
    while (outs.length < v.length) outs.push([0, 0]);
    return { c: L.closed, v, i: ins, o: outs };
  });
}

export function toLottie(m: Morph, o: LottieOptions = {}): object {
  const fps = o.fps ?? 60,
    dur = o.duration ?? 0.6,
    hold = o.hold ?? 0.6;
  const [, , vw, vh] = m.viewBox;
  const scale = (o.size ?? 512) / Math.max(vw, vh);
  const w = Math.round(vw * scale),
    h = Math.round(vh * scale);
  const color = o.color ?? "#13212b";
  const f1 = Math.round(dur * fps),
    f2 = Math.round((dur + hold) * fps),
    f3 = Math.round((2 * dur + hold) * fps);
  const op = Math.round((2 * dur + 2 * hold) * fps);
  const A = lottieShapes(m, 0),
    B = lottieShapes(m, 1);
  const ease = { o: { x: 0.65, y: 0 }, i: { x: 0.35, y: 1 } };
  const linear = { o: { x: 0, y: 0 }, i: { x: 1, y: 1 } };

  const shapeItems = A.map((sa, k) => ({
    ty: "sh",
    ind: k,
    nm: `Path ${k + 1}`,
    ks: {
      a: 1,
      k: [
        { t: 0, s: [sa], ...ease },
        { t: f1, s: [B[k]], ...linear },
        { t: f2, s: [B[k]], ...ease },
        { t: f3, s: [sa], ...linear },
        { t: op, s: [sa] },
      ],
    },
  }));

  const sA = m.style(0),
    sB = m.style(1);
  const paints: object[] = [];
  if (sA.stroke) {
    const animW = sA.strokeWidth !== sB.strokeWidth;
    paints.push({
      ty: "st",
      nm: "Stroke",
      bm: 0,
      c: { a: 0, k: lottieColor(sA.stroke, color) },
      o: { a: 0, k: 100 },
      w: animW
        ? {
            a: 1,
            k: [
              { t: 0, s: [n(sA.strokeWidth)], o: { x: [0.65], y: [0] }, i: { x: [0.35], y: [1] } },
              { t: f1, s: [n(sB.strokeWidth)], o: { x: [0], y: [0] }, i: { x: [1], y: [1] } },
              { t: f2, s: [n(sB.strokeWidth)], o: { x: [0.65], y: [0] }, i: { x: [0.35], y: [1] } },
              { t: f3, s: [n(sA.strokeWidth)] },
            ],
          }
        : { a: 0, k: n(sA.strokeWidth) },
      lc: { butt: 1, round: 2, square: 3 }[sA.lineCap],
      lj: { miter: 1, round: 2, bevel: 3 }[sA.lineJoin],
      ml: 4,
    });
  }
  if (sA.fill) {
    paints.push({
      ty: "fl",
      nm: "Fill",
      bm: 0,
      c: { a: 0, k: lottieColor(sA.fill, color) },
      o: { a: 0, k: 100 },
      r: sA.fillRule === "evenodd" ? 2 : 1,
    });
  }

  return {
    v: "5.7.4",
    fr: fps,
    ip: 0,
    op,
    w,
    h,
    nm: o.name ?? "morph",
    ddd: 0,
    assets: [],
    markers: [],
    layers: [
      {
        ddd: 0,
        ind: 1,
        ty: 4,
        nm: o.name ?? "morph",
        sr: 1,
        ao: 0,
        ip: 0,
        op,
        st: 0,
        bm: 0,
        ks: {
          o: { a: 0, k: 100 },
          r: { a: 0, k: 0 },
          p: { a: 0, k: [0, 0, 0] },
          a: { a: 0, k: [0, 0, 0] },
          s: { a: 0, k: [n(scale * 100), n(scale * 100), 100] },
        },
        shapes: [
          {
            ty: "gr",
            nm: "Morph",
            np: shapeItems.length + paints.length,
            bm: 0,
            it: [
              ...shapeItems,
              ...paints,
              {
                ty: "tr",
                nm: "Transform",
                p: { a: 0, k: [0, 0] },
                a: { a: 0, k: [0, 0] },
                s: { a: 0, k: [100, 100] },
                r: { a: 0, k: 0 },
                o: { a: 0, k: 100 },
                sk: { a: 0, k: 0 },
                sa: { a: 0, k: 0 },
              },
            ],
          },
        ],
      },
    ],
  };
}

/* ---------------------------------------------------------------------------
 * Agent tool: let an LLM call the engine with function calling.
 * Models are good at drawing two static states and bad at keeping point
 * structures compatible across time. The tool does the geometry.
 * ------------------------------------------------------------------------- */

export const MORPH_TOOL = {
  name: "morph_vector",
  description:
    "Create a smooth animation between two vector shapes. Pass the start and end state as SVG markup or SVG path data. " +
    "The engine normalises both to cubic Béziers, matches their points and returns a ready-to-ship animation in the requested format.",
  input_schema: {
    type: "object",
    properties: {
      from: { type: "string", description: "Start state: full <svg> markup or path data." },
      to: { type: "string", description: "End state: full <svg> markup or path data." },
      format: {
        type: "string",
        enum: ["animated_svg", "lottie", "react", "css", "path_frames"],
        description: "Output format. Default animated_svg.",
      },
      duration_ms: { type: "number", description: "Transition duration in milliseconds. Default 600." },
      frames: { type: "integer", description: "For path_frames: number of frames to sample. Default 10." },
      pairing: { type: "string", enum: ["auto", "order"], description: "How subpaths are paired. auto matches by position and size." },
    },
    required: ["from", "to"],
  },
} as const;

export interface MorphToolInput {
  from: string;
  to: string;
  format?: "animated_svg" | "lottie" | "react" | "css" | "path_frames";
  duration_ms?: number;
  frames?: number;
  pairing?: MorphOptions["pairing"];
}

/** Execute the tool. Returns plain JSON, suitable as a tool_result. Throws with a readable message on bad input. */
export function runMorphTool(input: MorphToolInput) {
  const m = createMorph(String(input.from), String(input.to), { pairing: input.pairing });
  const duration = (input.duration_ms ?? 600) / 1000;
  const s = m.plan.stats;
  const stats = {
    segments: s.matchedSegs,
    subpaths: m.plan.layout.length,
    splits: { from: s.splitsA, to: s.splitsB },
    padded_subpaths: s.padded,
    direction_flips: s.directionFlips,
  };
  switch (input.format ?? "animated_svg") {
    case "lottie":
      return { format: "lottie", stats, output: toLottie(m, { duration }) };
    case "react":
      return { format: "react", stats, output: toReactToggle(m, "MorphIcon", duration) };
    case "css":
      return { format: "css", stats, output: toCSS(m, { duration }) };
    case "path_frames": {
      const count = Math.max(2, Math.min(120, input.frames ?? 10));
      return { format: "path_frames", stats, viewBox: m.viewBox, output: Array.from({ length: count }, (_, i) => m.d(i / (count - 1))) };
    }
    default:
      return { format: "animated_svg", stats, output: toAnimatedSVG(m, { duration }) };
  }
}
