// Bundles src/workers/match.ts and the matcher into one script, saved as a string in
// src/workers/match.generated.ts, so particles() can start it from a Blob. Runs before build,
// typecheck and test.
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
// esbuild comes with tsup.
const esbuild = require(require.resolve('esbuild', { paths: [path.dirname(require.resolve('tsup/package.json'))] }));

const result = await esbuild.build({
  entryPoints: [path.join(here, '../src/workers/match.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
});
const code = result.outputFiles[0].text;
await writeFile(
  path.join(here, '../src/workers/match.generated.ts'),
  `// Generated by scripts/build-worker.mjs from src/workers/match.ts. Do not edit.\nexport const MATCH_WORKER = ${JSON.stringify(code)};\n`,
);
console.log(`match worker: ${(code.length / 1024).toFixed(1)} KB`);
