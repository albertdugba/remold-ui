export function Introduction() {
  return (
    <>
      <PageHeader title="Introduction">Remold animates interface changes without asking you to label anything.</PageHeader>
      <p>
        When the page changes, Remold compares what was on screen with what is there now, works out which element became which, and
        moves each one to its new place with a spring. Sort the list below: the whole list is rendered again, and nothing in it has an
        animation id.
      </p>
      <Demo>
        <FilesDemo />
      </Demo>

      <H2>Why no ids</H2>
      <p>
        Layout animation tools usually pair elements by a name you give them, such as <code>layoutId</code> or{" "}
        <code>view-transition-name</code>. That works until the markup is rewritten: a server response, a different component rendering the
        same data, content generated by a model. Remold pairs elements by what they are instead (their text, images, size, position and
        surroundings), so it also works on markup you don't control.
      </p>

      <H2>Packages</H2>
      <Definitions
        label={["Package", "What it does"]}
        rows={[
          { name: "@remold-ui/react", description: "Components and hooks for React. Start here if you use React." },
          { name: "@remold-ui/dom", description: "Transitions for any DOM element, text morphing, and View Transitions support." },
          { name: "@remold-ui/canvas", description: "Animated scenes and particles drawn on a canvas." },
          {
            name: "@remold-ui/core",
            description: "The matching, springs and shape morphing everything else is built on. No DOM, so it runs anywhere.",
          },
        ]}
      />

      <H2>Principles</H2>
      <ul>
        <li>
          <strong>Interruptible.</strong> Change state again mid-animation and everything heads for the new place from where it is, at the
          speed it was going.
        </li>
        <li>
          <strong>Springs, not durations.</strong> Motion is described as <code>{"{ duration, bounce }"}</code>, the way SwiftUI does it.
        </li>
        <li>
          <strong>Reduced motion.</strong> When the system asks for less motion, changes happen at once but are still announced.
        </li>
        <li>
          <strong>Small.</strong> The core has no dependencies, and each package can be used on its own.
        </li>
      </ul>
      <p>
        Next: <DocLink to="installation">Installation</DocLink>.
      </p>
    </>
  );
}

export function Installation() {
  return (
    <>
      <PageHeader title="Installation">Install the package for your framework. The others it needs come with it.</PageHeader>
      <H2>React</H2>
      <Code label="npm">{`npm install @remold-ui/react`}</Code>
      <Code label="pnpm">{`pnpm add @remold-ui/react`}</Code>
      <p>React 18 or later. The package ships ES modules, CommonJS and TypeScript types.</p>

      <H2>Without a framework</H2>
      <Code label="npm">{`npm install @remold-ui/dom`}</Code>
      <Code>{`
import { transition } from "@remold-ui/dom";

transition(list, () => {
  list.innerHTML = render(sortedItems);
});
`}</Code>

      <H2>Canvas and core</H2>
      <p>
        Install <code>@remold-ui/canvas</code> for scenes and particles, or <code>@remold-ui/core</code> on its own for the matching and
        spring maths, for example in a Web Worker or on the server.
      </p>
      <Note>
        Everything is tree-shakeable. Importing <code>Remold.Text</code> doesn't pull in the canvas code.
      </Note>
    </>
  );
}

export function QuickStart() {
  return (
    <>
      <PageHeader title="Quick start">Animate a list that sorts and filters, in a few lines.</PageHeader>
      <H2>Wrap the part that changes</H2>
      <p>
        Put <code>Remold.Layout</code> around the content and give it a <code>trigger</code>: any value that changes when the content
        does. Render your content as you normally would.
      </p>
      <Code>{`
import { Remold } from "@remold-ui/react";

function Files({ files, sort, kind }) {
  return (
    <Remold.Layout trigger={\`\${sort}:\${kind}\`}>
      {files.map((file) => (
        <Row key={file.name} file={file} />
      ))}
    </Remold.Layout>
  );
}
`}</Code>
      <Demo>
        <FilesDemo />
      </Demo>
      <p>
        React's <code>key</code> is still there for React's own reasons. Remold doesn't read it: it would animate the same if the rows
        were rebuilt from scratch.
      </p>

      <H2>Animate from an event handler</H2>
      <p>
        When there's no single value to watch, use <code>useRemold</code> and wrap the state change.
      </p>
      <Code>{`
const { ref, animate } = useRemold();

<ul ref={ref}>{items.map(renderItem)}</ul>
<button onClick={() => animate(() => setItems(shuffle(items)))}>Shuffle</button>
`}</Code>

      <H2>Change text in place</H2>
      <Code>{`<Remold.Text>{status}</Remold.Text>`}</Code>
      <p>
        Letters the old and new text share stay and slide into place; the rest fade in and out. See <DocLink to="react/text">Text</DocLink>.
      </p>

      <H2>Next steps</H2>
      <ul>
        <li>
          <DocLink to="concepts/matching">How matching works</DocLink>, and how to steer it.
        </li>
        <li>
          <DocLink to="concepts/springs">Springs</DocLink>: choosing how things move.
        </li>
        <li>
          <DocLink to="examples/interfaces">Examples</DocLink> you can copy.
        </li>
      </ul>
    </>
  );
}
