// Reads Great Vibes (SIL Open Font License 1.1) once and writes the outlines of its letters as path
// data, so the "Adopt your signature" example can set a typed name in a script without loading a
// font in the browser. Great Vibes is on Google Fonts; pass its .ttf or .woff file:
//   node scripts/extract-signature-glyphs.mjs path/to/GreatVibes-Regular.woff
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const file = process.argv[2];
if (!file) throw new Error("Pass the path to GreatVibes-Regular.ttf or .woff");
const buffer = readFileSync(file);
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
const upm = font.unitsPerEm;

// Letters, digits and the punctuation people put in their names.
const chars = [..." ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789.'-&"];
const glyphs = {};
for (const ch of chars) {
  const glyph = font.charToGlyph(ch);
  // At font size = units per em, path units are font units; y points down with the baseline at 0.
  const d = glyph.getPath(0, 0, upm).toPathData(1);
  glyphs[ch] = { d, adv: glyph.advanceWidth };
}
const kern = {};
for (const a of chars) {
  for (const b of chars) {
    const k = font.getKerningValue(font.charToGlyph(a), font.charToGlyph(b));
    if (k) kern[a + b] = k;
  }
}

const out = `// Generated by scripts/extract-signature-glyphs.mjs from Great Vibes Regular. Do not edit.
// Great Vibes: Copyright 2012 The Great Vibes Project Authors (https://github.com/googlefonts/great-vibes),
// licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org).
export const SCRIPT = ${JSON.stringify({ upm, asc: font.ascender, desc: font.descender, glyphs, kern })} as const;
`;
writeFileSync(new URL("../components/demos/signature-glyphs.ts", import.meta.url), out);
console.log(`${chars.length} glyphs, ${Object.keys(kern).length} kerning pairs, ${(out.length / 1024).toFixed(1)} KB`);
