// Reads Barlow Condensed (SIL Open Font License 1.1) once and writes its glyph outlines as path
// data, so the "Letters as geometry" example can bend real letters without parsing a font in the
// browser. Run with: node scripts/extract-glyphs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import opentype from "opentype.js";

const require = createRequire(import.meta.url);
const file = require.resolve("@fontsource/barlow-condensed/files/barlow-condensed-latin-700-normal.woff");
const buffer = readFileSync(file);
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
const upm = font.unitsPerEm;

const chars = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i));
const glyphs = {};
for (const ch of chars) {
  const glyph = font.charToGlyph(ch);
  // At font size = units per em, path units are font units; y points down with the baseline at 0.
  const d = glyph.getPath(0, 0, upm).toPathData(1);
  glyphs[ch] = { d, adv: glyph.advanceWidth };
}
const kern = {};
for (const a of chars) {
  for (const b of chars) {
    const k = font.getKerningValue(font.charToGlyph(a), font.charToGlyph(b));
    if (k) kern[a + b] = k;
  }
}

const out = `// Generated by scripts/extract-glyphs.mjs from Barlow Condensed Bold. Do not edit.
// Barlow Condensed: Copyright 2017 The Barlow Project Authors (https://github.com/jpt/barlow),
// licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org).
export const GLYPHS = ${JSON.stringify({ upm, asc: font.ascender, desc: font.descender, glyphs, kern })} as const;
`;
writeFileSync(new URL("../components/demos/glyphs-data.ts", import.meta.url), out);
console.log(`${chars.length} glyphs, ${Object.keys(kern).length} kerning pairs, ${(out.length / 1024).toFixed(1)} KB`);
